#!/usr/bin/env bash
# One-time setup on a Proxmox VE 8 host for TinyBox.
#  - NAT bridge vmbr1 (10.77.0.0/16) for the tiny containers
#  - SSH port forwards: public port SSH_PORT_BASE+i  ->  container i, port 22
#  - basic abuse protection (no SMTP, no access to the host from containers)
#  - API user + token with only the privileges TinyBox needs
#  - Alpine container template
#
# Usage:  WAN_IF=vmbr0 bash proxmox-setup.sh
# Values must match the backend .env (VMID_MIN/MAX, NAT_SUBNET_PREFIX, SSH_PORT_BASE).
set -euo pipefail

WAN_IF="${WAN_IF:-vmbr0}"
BRIDGE="${BRIDGE:-vmbr1}"
NAT_PREFIX="${NAT_PREFIX:-10.77}"
VMID_MIN="${VMID_MIN:-10000}"
VMID_MAX="${VMID_MAX:-10999}"
SSH_PORT_BASE="${SSH_PORT_BASE:-20000}"
STORAGE_TMPL="${STORAGE_TMPL:-local}"
POOL="${POOL:-tinybox}"

[[ $EUID -eq 0 ]] || { echo "run as root on the Proxmox host"; exit 1; }
command -v pveum >/dev/null || { echo "pveum not found – is this a Proxmox host?"; exit 1; }

echo "==> NAT bridge $BRIDGE"
if ! grep -q "iface $BRIDGE" /etc/network/interfaces; then
  cat >> /etc/network/interfaces <<IFACE

auto $BRIDGE
iface $BRIDGE inet static
    address ${NAT_PREFIX}.0.1/16
    bridge-ports none
    bridge-stp off
    bridge-fd 0
    post-up   /usr/local/sbin/tinybox-nat up
    pre-down  /usr/local/sbin/tinybox-nat down
IFACE
fi

echo "==> NAT / port-forward script"
cat > /usr/local/sbin/tinybox-nat <<NAT
#!/usr/bin/env bash
# Generated by TinyBox proxmox-setup.sh
set -e
OP=\${1:-up}; A=-A; [[ \$OP == down ]] && A=-D
echo 1 > /proc/sys/net/ipv4/ip_forward
ipt() { iptables "\$@" 2>/dev/null || true; }
ipt -t nat \$A POSTROUTING -s ${NAT_PREFIX}.0.0/16 -o ${WAN_IF} -j MASQUERADE
# conntrack zones for firewall=1 bridges
ipt -t raw \$A PREROUTING -i fwbr+ -j CT --zone 1
# Block outbound SMTP (spam) and access to the host itself
ipt \$A FORWARD -s ${NAT_PREFIX}.0.0/16 -p tcp -m multiport --dports 25,465,587 -j REJECT
ipt \$A INPUT -i ${BRIDGE} -p tcp -m multiport --dports 22,8006,3128,111 -j DROP
# SSH forwards: port ${SSH_PORT_BASE}+i -> container for vmid ${VMID_MIN}+i
for ((i=0; i<=${VMID_MAX}-${VMID_MIN}; i++)); do
  n=\$((i + 2)); ip="${NAT_PREFIX}.\$((n >> 8)).\$((n & 255))"
  ipt -t nat \$A PREROUTING -i ${WAN_IF} -p tcp --dport \$((${SSH_PORT_BASE} + i)) -j DNAT --to-destination \$ip:22
done
NAT
chmod +x /usr/local/sbin/tinybox-nat
ifreload -a || ifup "$BRIDGE" || true
/usr/local/sbin/tinybox-nat up

echo "==> sysctl"
cat > /etc/sysctl.d/90-tinybox.conf <<SYS
net.ipv4.ip_forward=1
# lots of tiny containers need lots of inotify/keys
fs.inotify.max_user_instances=8192
fs.inotify.max_user_watches=1048576
kernel.keys.maxkeys=20000
SYS
sysctl --system >/dev/null

echo "==> API role, user, token, pool"
PRIVS="VM.Allocate VM.Audit VM.PowerMgmt VM.Config.CPU VM.Config.Memory VM.Config.Disk VM.Config.Network VM.Config.Options Datastore.AllocateSpace Datastore.Audit Sys.Audit SDN.Use Pool.Audit"
pveum role add TinyBox --privs "$PRIVS" 2>/dev/null || pveum role modify TinyBox --privs "$PRIVS"
pveum user add tinybox@pve --comment "TinyBox API" 2>/dev/null || true
pveum pool add "$POOL" 2>/dev/null || true
pveum acl modify / --users tinybox@pve --roles TinyBox
if ! pveum user token list tinybox@pve 2>/dev/null | grep -q " api "; then
  echo "---- SAVE THIS TOKEN SECRET (PROXMOX_TOKEN_SECRET) ----"
  pveum user token add tinybox@pve api --privsep 0
  echo "PROXMOX_TOKEN_ID=tinybox@pve!api"
fi

echo "==> Alpine template"
pveam update >/dev/null
TMPL=$(pveam available --section system | awk '{print $2}' | grep '^alpine-' | sort -V | tail -1)
pveam list "$STORAGE_TMPL" | grep -q "$TMPL" || pveam download "$STORAGE_TMPL" "$TMPL"
echo "PROXMOX_TEMPLATE=${STORAGE_TMPL}:vztmpl/${TMPL}"

echo
echo "Done. Put the values above into tinybox/backend/.env and set PROXMOX_MOCK=false."
echo "Open TCP ${SSH_PORT_BASE}-$((SSH_PORT_BASE + VMID_MAX - VMID_MIN)) on any upstream firewall."
