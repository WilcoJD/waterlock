#!/usr/bin/env node
/**
 * node src/build.js
 *  1. Bundles content/seed into functions/_lib/seed-data.js (imported by the functions).
 *  2. Exports every published page, post and listing as static HTML into public/, plus sitemap and robots.
 *
 * The static export is what the site serves when the database isn't configured, and it is also a
 * complete, host-anywhere copy of the site.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, rmSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SEED_DIR = join(ROOT, "content", "seed");
const PUBLIC = join(ROOT, "public");

export function readSeed() {
  const readJson = (p) => JSON.parse(readFileSync(p, "utf8"));
  const settings = readJson(join(SEED_DIR, "settings.json"));
  const pages = readdirSync(join(SEED_DIR, "pages")).filter((f) => f.endsWith(".json")).sort().map((f) => readJson(join(SEED_DIR, "pages", f)));
  const postsDir = join(SEED_DIR, "posts");
  const posts = existsSync(postsDir) ? readdirSync(postsDir).filter((f) => f.endsWith(".json")).sort().map((f) => readJson(join(postsDir, f))) : [];
  const backlinks = existsSync(join(SEED_DIR, "backlinks.json")) ? readJson(join(SEED_DIR, "backlinks.json")) : [];
  const redirects = existsSync(join(SEED_DIR, "redirects.json")) ? readJson(join(SEED_DIR, "redirects.json")) : [];
  return { settings, pages, posts, backlinks, redirects, version: new Date().toISOString().slice(0, 10) };
}

export function writeSeedModule(seed) {
  const out = `// GENERATED by src/build.js from content/seed — do not edit by hand.\nexport default ${JSON.stringify(seed)};\n`;
  writeFileSync(join(ROOT, "functions", "_lib", "seed-data.js"), out);
}

export async function exportStatic(seed) {
  const { renderPage, renderPost, renderListing, renderSitemap, renderFeed, navFromPages, footerNavFromPages } = await import("../functions/_lib/render.js");
  const { getTheme } = await import("../functions/_lib/themes.js");
  const { normalisePage, normalisePost } = await import("../functions/_lib/db.js");
  const site = seed.settings.site;
  const pages = seed.pages.map(normalisePage).filter((p) => p.status === "published");
  const posts = seed.posts.map(normalisePost).filter((p) => p.status === "published").sort((a, b) => String(b.published_at).localeCompare(String(a.published_at)));
  const events = pages.filter((p) => p.kind === "event");
  const ctx = { site, theme: getTheme(site.theme), pages, events, posts: posts.slice(0, 6), hasBlog: posts.length > 0, hasEvents: events.length > 0, nav: navFromPages(pages), footerNav: footerNavFromPages(pages) };
  const write = (rel, content) => { const p = join(PUBLIC, rel); mkdirSync(dirname(p), { recursive: true }); writeFileSync(p, content); };

  // remove previously exported HTML so deleted pages disappear (assets are kept)
  const walk = (dir) => { for (const f of readdirSync(dir, { withFileTypes: true })) { const p = join(dir, f.name); if (f.isDirectory()) { if (f.name !== "assets") walk(p); } else if (f.name.endsWith(".html")) rmSync(p); } };
  walk(PUBLIC);

  let count = 0;
  for (const page of pages) {
    const name = page.slug === site.homepage_slug ? "index" : page.slug;
    write(`${name}.html`, renderPage(page, ctx)); count++;
    if (page.slug === "index" && site.homepage_slug !== "index") { write("index-page.html", renderPage(page, ctx)); }
  }
  const nf = seed.pages.map(normalisePage).find((p) => p.slug === "404");
  if (nf) write("404.html", renderPage(nf, ctx));
  for (const post of posts) { write(`blog/${post.slug}.html`, renderPost(post, ctx)); count++; }
  if (posts.length) {
    write("blog/index.html", renderListing({ kind: "posts", items: posts, title: "News", eyebrow: "From the hotel", lede: `News and articles from ${site.name}.`, path: "/blog", description: `News and articles from ${site.name}, ${site.address.town}.` }, ctx));
    write("blog/feed.xml", renderFeed(posts.slice(0, 20), site));
  }
  if (events.length && !pages.some((p) => p.slug === "events")) {
    write("events/index.html", renderListing({ kind: "events", items: events, title: "Events & packages", eyebrow: "Through the year", lede: "Burns Night to Hogmanay, family lunches to party nights: what we host and arrange.", path: "/events", description: `Events, celebrations and packages at ${site.name}, ${site.address.town}: Burns Night, Christmas, Hogmanay, family lunches and more.` }, ctx));
  }
  const base = (site.site_url || "").replace(/\/$/, "");
  const urls = [base + "/"];
  for (const p of pages) if (p.kind !== "system" && p.slug !== "index" && p.slug !== site.homepage_slug && !(p.meta && p.meta.noindex)) urls.push(`${base}/${p.slug}`);
  if (events.length) urls.push(base + "/events");
  if (posts.length) { urls.push(base + "/blog"); for (const p of posts) urls.push(`${base}/blog/${p.slug}`); }
  write("sitemap.xml", renderSitemap(urls));
  write("robots.txt", `User-agent: *\nAllow: /\nDisallow: /admin\n\nSitemap: ${base}/sitemap.xml\n`);
  return count;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const seed = readSeed();
  writeSeedModule(seed);
  console.log(`seed-data.js: ${seed.pages.length} pages, ${seed.posts.length} posts, ${seed.backlinks.length} backlinks, ${seed.redirects.length} redirects`);
  const n = await exportStatic(seed);
  console.log(`static export: ${n} pages/posts written to public/`);
}
